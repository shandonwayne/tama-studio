// Cursive — flowing lowercase cross-stitch style, 8-wide × 10-tall grid
function gc(rows: string[]): Glyph {
  const cells: Glyph = [];
  rows.forEach((row, y) => {
    for (let x = 0; x < row.length; x++) {
      if (row[x] === '#') cells.push([x, y]);
    }
  });
  return cells;
}

