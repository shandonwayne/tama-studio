// Pixel font library — 5×7 grid per character.
// Each glyph is a set of [x, y] cell offsets that should be filled.

export type Glyph = [number, number][];

const W = 5;
const H = 7;

function g(rows: string[]): Glyph {
  const cells: Glyph = [];
  rows.forEach((row, y) => {
    for (let x = 0; x < row.length; x++) {
      if (row[x] === '#') cells.push([x, y]);
    }
  });
  return cells;
}

