export const AVAILABLE_CHARS = [...'ABCDEFGHIJKLMNOPQRSTUVWXYZ', ...'0123456789'];

export function textToCells(
  text: string,
  originX: number,
  originY: number,
  font: Record<string, Glyph> = gothicFont,
  spacing = 1
): [number, number][] {
  const cells: [number, number][] = [];
  let cursorX = originX;
  for (const rawChar of text.toUpperCase()) {
    const glyph = font[rawChar];
    if (glyph) {
      for (const [gx, gy] of glyph) {
        cells.push([cursorX + gx, originY + gy]);
      }
    }
    cursorX += W + spacing;
  }
  return cells;
}

export function measureText(text: string, spacing = 1): number {
  const len = text.length;
  if (len === 0) return 0;
  return len * W + (len - 1) * spacing;
}
